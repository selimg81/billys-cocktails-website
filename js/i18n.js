function applyLang(lang) {
  const t = TRANSLATIONS[lang] || TRANSLATIONS.de;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.dataset.i18n;
    if (t[k] !== undefined) el.textContent = t[k];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const k = el.dataset.i18nPh;
    if (t[k] !== undefined) el.setAttribute('placeholder', t[k]);
  });
  document.querySelectorAll('.lang-label').forEach(el => { el.textContent = lang.toUpperCase(); });
  localStorage.setItem('billy-lang', lang);
  document.documentElement.lang = lang;
}

document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('billy-lang') || 'de';
  applyLang(saved);
  document.querySelectorAll('#lang-toggle').forEach(btn => {
    btn.addEventListener('click', () => {
      applyLang((localStorage.getItem('billy-lang') || 'de') === 'de' ? 'en' : 'de');
    });
  });
});
